final translationCatalog = <String, Map<String, String>>{
  for (final language in languageCodes.keys) language: {},
}..addAll(_buildCatalog());

Map<String, Map<String, String>> _buildCatalog() {
  final result = <String, Map<String, String>>{};
  final languages = languageCodes.keys.toList();
  for (final line in _textRows.trim().split('\n')) {
    final row = line.split('|');
    if (row.length != languages.length) {
      throw StateError('Invalid translation: ${row.first}');
    }
    for (int i = 0; i < languages.length; i++) {
      (result[languages[i]] ??= {})[row.first.trim().toLowerCase()] = row[i]
          .trim();
    }
  }
  return result;
}

String translate(
  String text,
  String language, [
  Map<String, Object> parameters = const {},
]) {
  var result = language == 'English'
      ? text
      : translationCatalog[language]?[text.trim().toLowerCase()] ?? text;
  for (final entry in parameters.entries) {
    result = result.replaceAll('{${entry.key}}', entry.value.toString());
  }
  return result;
}
